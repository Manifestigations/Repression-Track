/* =============================================================================
   GEOGRAPHY — two fields, two different questions
   -----------------------------------------------------------------------------
   `scope`  legacy coarse bucket, kept so the old territory filter keeps working:
            "herault" | "occitanie" | "national" (meaning: outside Hérault and
            Occitanie — NOT "decided by a national court").
   `geo`    precise placement, one id from src/client/geo.ts. This is what the
            four-level selector (country > region > department > city) uses.
            Rules applied in this file:
              - a case sits where the measure at issue applies (city of the
                préfecture / tribunal), not where the judge sits;
              - a Conseil d'État ruling, a ministerial circular, a parliamentary
                commission and national statistics are "national": they bind
                everywhere, so they stay visible under every filter and carry
                an "applies across all of France" badge;
              - a case spanning two territories is filed under the lead
                department, with the other territory named in the note.
   ========================================================================== */

